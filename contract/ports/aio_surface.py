"""gpframe.aio(非同期版)の公開 API の形。

同期版の形(`surface.py`)とは型を共有しない。テストの `@binds[...]` によって、
実装がこの形を満たすことが型検査で確かめられる。
"""

from __future__ import annotations

from collections.abc import Callable, Coroutine, Sequence
from types import TracebackType
from typing import Protocol, Self, TypeVar, TypeVarTuple

R = TypeVar("R")
R_co = TypeVar("R_co", covariant=True)
Ts = TypeVarTuple("Ts")


class AsyncSessionReport(Protocol):
    """不完全だった非同期のサブセッションの報告。"""

    @property
    def broken(self) -> tuple[AsyncFrame[object], ...]: ...
    @property
    def stuck(self) -> tuple[AsyncFrame[object], ...]: ...
    @property
    def errors(self) -> tuple[BaseException, ...]: ...


class StopHandle(Protocol):
    """非同期版の停止コールバックの登録。"""

    def cancel(self) -> None: ...


class AsyncFrame(Protocol[R_co]):
    """ループ上のタスクとして動く処理のハンドル。"""

    @property
    def name(self) -> str: ...
    @property
    def running(self) -> bool: ...
    @property
    def succeeded(self) -> bool: ...
    @property
    def stopped(self) -> bool: ...
    @property
    def error(self) -> BaseException | None: ...
    @property
    def incomplete(self) -> AsyncSessionReport | None: ...
    @property
    def stop_errors(self) -> tuple[BaseException, ...]: ...
    async def result(self, timeout: float | None = None) -> R_co: ...
    async def wait(self, timeout: float | None = None) -> bool: ...
    def ignore(self) -> None: ...
    def escalate(self, reason: str = "") -> None: ...


class AsyncContext(Protocol):
    """非同期のルーティンに渡される実行環境。"""

    @property
    def name(self) -> str: ...
    @property
    def stopping(self) -> bool: ...
    def on_stop(self, callback: Callable[[], object]) -> StopHandle: ...
    def session(self, *, timeout: float | None = None) -> AsyncSession: ...


class AsyncSession(Protocol):
    """非同期のフレームを管理するスコープ。"""

    @property
    def stopping(self) -> bool: ...
    def spawn(
        self,
        fn: Callable[[AsyncContext, *Ts], Coroutine[object, object, R]],
        *args: *Ts,
        name: str | None = None,
    ) -> AsyncFrame[R]: ...
    def running(self) -> bool: ...
    def broken(self) -> Sequence[AsyncFrame[object]]: ...
    async def wait(self, timeout: float | None = None) -> bool: ...
    async def wait_broken(
        self, timeout: float | None = None, *, idle: bool = False
    ) -> Sequence[AsyncFrame[object]]: ...
    def stop(self) -> None: ...
    async def __aenter__(self) -> Self: ...
    async def __aexit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> bool | None: ...


class LoopMonitor(Protocol):
    """ループの応答を監視するヘルスチェック。"""

    @property
    def threshold(self) -> float: ...
    @property
    def interval(self) -> float: ...
    @property
    def stalled(self) -> bool: ...
    @property
    def lag(self) -> float: ...
    @property
    def errors(self) -> tuple[BaseException, ...]: ...
    async def __aenter__(self) -> Self: ...
    async def __aexit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> bool | None: ...
