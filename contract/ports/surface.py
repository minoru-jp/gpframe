"""gpframe の公開 API の形。

実装はこの Protocol を満たす。テストの `@binds[...]` によって、実装が
この形を満たすことが型検査で確かめられる。
"""

from __future__ import annotations

from collections.abc import Callable, Coroutine, Iterator, Sequence
from types import TracebackType
from typing import Protocol, Self, TypeVar, TypeVarTuple, overload

R = TypeVar("R")
R_co = TypeVar("R_co", covariant=True)
T = TypeVar("T")
Ts = TypeVarTuple("Ts")


class SessionReport(Protocol):
    """不完全だったサブセッションの報告。"""

    @property
    def broken(self) -> tuple[Frame[object], ...]: ...
    @property
    def stuck(self) -> tuple[Frame[object], ...]: ...
    @property
    def errors(self) -> tuple[BaseException, ...]: ...


class StopHandle(Protocol):
    """停止コールバックの登録。"""

    def cancel(self) -> None: ...


class Frame(Protocol[R_co]):
    """一つのスレッドで動く処理のハンドル。"""

    @property
    def name(self) -> str: ...
    @property
    def running(self) -> bool: ...
    @property
    def succeeded(self) -> bool: ...
    @property
    def stopped(self) -> bool: ...
    @property
    def error(self) -> BaseException | None: ...
    @property
    def incomplete(self) -> SessionReport | None: ...
    @property
    def stop_errors(self) -> tuple[BaseException, ...]: ...
    def result(self, timeout: float | None = None) -> R_co: ...
    def wait(self, timeout: float | None = None) -> bool: ...
    def ignore(self) -> None: ...
    def escalate(self, reason: str = "") -> None: ...


class Context(Protocol):
    """ルーティンに渡される実行環境。"""

    @property
    def name(self) -> str: ...
    @property
    def stopping(self) -> bool: ...
    def wait_stop(self, timeout: float | None = None) -> bool: ...
    def on_stop(self, callback: Callable[[], object]) -> StopHandle: ...
    def session(self, *, timeout: float | None = None) -> Session: ...


class Session(Protocol):
    """フレームを管理するスコープ。"""

    @property
    def stopping(self) -> bool: ...

    @overload
    def spawn(
        self,
        fn: Callable[[Context, *Ts], Coroutine[object, object, R]],
        *args: *Ts,
        name: str | None = None,
    ) -> Frame[R]: ...
    @overload
    def spawn(
        self,
        fn: Callable[[Context, *Ts], R],
        *args: *Ts,
        name: str | None = None,
    ) -> Frame[R]: ...
    # 実行時に Session.spawn が名前を持つよう、実装側のシグネチャも置く。
    def spawn(
        self,
        fn: Callable[..., object],
        *args: object,
        name: str | None = None,
    ) -> Frame[object]: ...

    def wait(self, timeout: float | None = None) -> bool: ...
    def running(self) -> bool: ...
    def broken(self) -> Sequence[Frame[object]]: ...
    def wait_broken(
        self, timeout: float | None = None, *, idle: bool = False
    ) -> Sequence[Frame[object]]: ...
    def stop(self) -> None: ...
    def __enter__(self) -> Self: ...
    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> bool | None: ...


class Shared(Protocol[T]):
    """型の固定された共有セル。"""

    @property
    def type(self) -> type[T]: ...
    def get(self) -> T: ...
    def set(self, value: T) -> None: ...
    def swap(self, value: T) -> T: ...
    def apply(self, fn: Callable[[T], T]) -> T: ...


class Channel(Protocol[T]):
    """フレーム間で値を順に受け渡す、停止で受け取りの待ちが解ける FIFO。"""

    @property
    def type(self) -> type[T]: ...
    @property
    def maxsize(self) -> int: ...
    @property
    def closed(self) -> bool: ...
    @overload
    def put(self, item: T) -> None: ...
    @overload
    def put(self, item: T, ctx: Context, timeout: float | None = None) -> bool: ...
    def put(
        self, item: T, ctx: Context | None = None, timeout: float | None = None
    ) -> bool | None: ...
    def get(self, ctx: Context, timeout: float | None = None) -> T | None: ...
    def receive(self, ctx: Context) -> Iterator[T]: ...
    def close(self) -> None: ...
